function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
    const dict = I18N[currentFleetLang()];
    return (dict && dict[key]) || key;
}

function fill(s, vars) {
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
}

// Static markup: elements carrying data-i18n use their original English text
// as the key (captured on first pass, whitespace-normalized so multi-line
// markup still matches; locale switches stay reversible).
function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        if (!el.dataset.i18nKey) el.dataset.i18nKey = el.textContent.trim().replace(/\s+/g, ' ');
        el.textContent = t(el.dataset.i18nKey);
    });
}

// Tooltips, placeholders and labels, addressed by id.
const ATTRS = [
    ['srcChip', 'title', 'Every reading is taken by this browser'],
    ['exportPng', 'title', 'Save the results as an image'],
    ['exportJson', 'title', 'Save the results as JSON'],
    ['reachSearch', 'placeholder', 'filter by name, host or region…'],
    ['reachRegionFilter', 'aria-label', 'Filter by region'],
];
function applyAttrI18n() {
    ATTRS.forEach(([id, attr, key]) => {
        const el = document.getElementById(id);
        if (el) el.setAttribute(attr, t(key));
    });
}

// Words the app wrote at run time (status, verdicts, units): each carries its
// English key in data-tkey and any {placeholders} in data-tvars.
function applyDynamicI18n() {
    document.querySelectorAll('[data-tkey]').forEach((el) => {
        let vars = null;
        try { vars = el.dataset.tvars ? JSON.parse(el.dataset.tvars) : null; } catch (e) { vars = null; }
        el.textContent = fill(t(el.dataset.tkey), vars);
    });
}

function applyI18n() {
    document.documentElement.lang = currentFleetLang();
    applyStaticI18n();
    applyAttrI18n();
    applyDynamicI18n();
}

document.addEventListener('DOMContentLoaded', applyI18n);
window.addEventListener('carino:langchange', applyI18n);

// carino-navbar.js greets through window.t; the app modules read the same handle.
window.t = t;
window.CarinoI18n = { t, apply: applyI18n };
